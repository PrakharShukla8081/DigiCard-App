export type CardCopyKey = keyof typeof CARD_COPY.en;

const API_ERROR_KEYS: Record<string, CardCopyKey> = {
  "Please enter your name": "pleaseEnterName",
  "Enter a valid email": "validEmail",
  "Enter a valid phone number.": "validPhone",
  "Enter your phone number or email so we can reply.": "emailOrPhone",
  "Please agree to be contacted": "consentRequired",
  "You have sent several enquiries already. Please try again later.": "tryLater",
  "Enquiries are not enabled for this card.": "formUnavailable",
};

export function cardText(language: CardLanguage, key: CardCopyKey, values: Record<string, string> = {}) {
  return CARD_COPY[language][key].replace(/\{(\w+)\}/g, (_match, name: string) => values[name] || "");
}

export function localizeCardError(message: string, language: CardLanguage) {
  return cardText(language, API_ERROR_KEYS[message] || "sendFailed");
}

export function cardLanguageStorageKey(orgSlug: string) {
  return `beno-card-language:${orgSlug}`;
}

export function browserCardLanguage(storageKey = "beno-card-language:default"): CardLanguage {
  try {
    const stored = localStorage.getItem(storageKey);
    if (stored === "en" || stored === "hi") return stored;
  } catch {
    // Storage can be unavailable in private browsing; use the browser language instead.
  }
  return /^hi(?:-|$)/i.test(navigator.language || "") ? "hi" : "en";
}
